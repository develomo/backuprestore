def save_pacing_plan(plan, output_path=None):
    output_path = Path(output_path or REPORT_DIR / "viral_pacing_plan.json")
    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text(json.dumps(plan, indent=2, ensure_ascii=False, default=str), encoding="utf-8")
    return str(output_path)


def load_pacing_plan(path):
    return json.loads(Path(path).read_text(encoding="utf-8"))


def viral_pacing_report(total_duration=60, mode="SHORT", niche=None, render_count=0):
    plan = build_viral_pacing_plan(total_duration, mode=mode, niche=niche, render_count=render_count)
    return {
        "output_dir": str(OUTPUT_DIR),
        "profiles": PACING_PROFILES,
        "section_rules": SECTION_RULES,
        "resolved_profile": _profile(niche=niche, mode=mode, render_count=render_count),
        "sections": build_sections(total_duration, mode=mode, niche=niche),
        "density": pacing_density_report(plan),
        "plan": plan,
    }


class ViralPacingEngine:
    def __init__(self, mode="SHORT", niche=None, render_count=0):
        self.mode = _mode_key(mode)
        self.niche = niche or "default"
        self.render_count = int(render_count or 0)

    def build(self, total_duration, max_clips=500):
        return build_viral_pacing_plan(total_duration, mode=self.mode, niche=self.niche, render_count=self.render_count, max_clips=max_clips)

    def sections(self, total_duration):
        return build_sections(total_duration, mode=self.mode, niche=self.niche)

    def report(self, total_duration=60):
        return viral_pacing_report(total_duration=total_duration, mode=self.mode, niche=self.niche, render_count=self.render_count)

    def save(self, total_duration, output_path=None):
        return save_pacing_plan(self.build(total_duration), output_path=output_path)


