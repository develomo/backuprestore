def _mode_key(mode="SHORT"):
    mode = str(mode or "SHORT").upper()
    return "LONG" if mode in ("LONG", "YOUTUBE_LONG", "HORIZONTAL") else "SHORT"


def _resolve_niche(niche=None):
    key = str(niche or "default").strip().lower()
    return key if key in PACING_PROFILES else "default"


def _profile(niche=None, mode="SHORT", render_count=0):
    key = _resolve_niche(niche)
    p = dict(PACING_PROFILES[key])
    offset = ((int(render_count or 0) % 7) - 3) * 0.04
    if _mode_key(mode) == "LONG":
        p["min_clip"] = max(2.0, p["long_min"] + offset)
        p["max_clip"] = max(p["min_clip"] + 0.8, p["long_max"] + offset)
    else:
        p["min_clip"] = max(0.6, p["short_min"] + offset)
        p["max_clip"] = max(p["min_clip"] + 0.5, p["short_max"] + offset)
    p["niche"] = key
    p["mode"] = _mode_key(mode)
    return p


def clamp(value, low, high):
    return max(low, min(high, float(value)))


def section_for_progress(progress):
    progress = clamp(progress, 0.0, 1.0)
    if progress < 0.12:
        return "hook"
    if progress < 0.25:
        return "setup"
    if progress < 0.78:
        return "body"
    if progress < 0.92:
        return "payoff"
    return "ending"


def section_adjusted_duration(base_duration, section, profile):
    rule = SECTION_RULES.get(section, SECTION_RULES["body"])
    speed = float(rule.get("speed", 1.0))
    duration = float(base_duration) / max(0.2, speed)
    if section == "hook":
        duration *= 0.82
    if section == "ending":
        duration *= 1.08
    if profile.get("mode") == "LONG" and section == "body":
        duration *= 1.10
    return max(0.35, duration)


def choose_duration_for_section(section, profile, rng):
    min_clip = float(profile["min_clip"])
    max_clip = float(profile["max_clip"])
    base = rng.uniform(min_clip, max_clip)
    return section_adjusted_duration(base, section, profile)


def build_viral_pacing_plan(total_duration, mode="SHORT", niche=None, render_count=0, render_plan=None, max_clips=500):
    total_duration = max(0.05, float(total_duration or 0.0))
    profile = _profile(niche=niche, mode=mode, render_count=render_count)
    rng = random.Random((int(render_count or 0) + 89) * 1009 + int(total_duration * 10))
    cursor = 0.0
    plan = []
    index = 0
    while cursor < total_duration - 0.001 and index < int(max_clips):
        progress = cursor / max(total_duration, 0.01)
        section = section_for_progress(progress)
        duration = choose_duration_for_section(section, profile, rng)
        remaining = total_duration - cursor
        if remaining < duration:
            duration = remaining
        if duration <= 0.05:
            break
        end = cursor + duration
        plan.append({
            "clip_index": index,
            "start": round(cursor, 3),
            "end": round(end, 3),
            "duration": round(duration, 3),
            "section": section,
            "priority": SECTION_RULES.get(section, {}).get("priority", 0.5),
            "progress": round(progress, 4),
        })
        cursor = end
        index += 1
    return rebalance_last_segment(plan, total_duration)


def rebalance_last_segment(plan, total_duration):
    if not plan:
        return []
    total_duration = float(total_duration)
    if abs(plan[-1]["end"] - total_duration) > 0.05:
        plan[-1]["end"] = round(total_duration, 3)
        plan[-1]["duration"] = round(total_duration - plan[-1]["start"], 3)
    if len(plan) >= 2 and plan[-1]["duration"] < 0.45:
        extra = plan[-1]["duration"]
        plan[-2]["end"] = plan[-1]["end"]
        plan[-2]["duration"] = round(plan[-2]["duration"] + extra, 3)
        plan.pop()
    for i, item in enumerate(plan):
        item["clip_index"] = i
    return plan


def build_fast_hook_plan(total_duration, mode="SHORT", niche=None, render_count=0):
    profile = _profile(niche=niche, mode=mode, render_count=render_count)
    if _mode_key(mode) == "LONG":
        hook_duration = min(4.0, max(2.5, total_duration * 0.025))
    else:
        hook_duration = min(3.5, max(1.6, total_duration * profile.get("hook_ratio", 0.16)))
    return {
        "start": 0.0,
        "end": round(hook_duration, 3),
        "duration": round(hook_duration, 3),
        "section": "hook",
        "style": "fast_retention",
    }


def build_sections(total_duration, mode="SHORT", niche=None):
    total_duration = max(0.05, float(total_duration or 0.0))
    if _mode_key(mode) == "LONG":
        sections = [
            {"section": "hook", "start": 0.0, "end": min(12.0, total_duration * 0.04)},
            {"section": "setup", "start": min(12.0, total_duration * 0.04), "end": min(total_duration * 0.20, 90.0)},
            {"section": "body", "start": min(total_duration * 0.20, 90.0), "end": total_duration * 0.78},
            {"section": "payoff", "start": total_duration * 0.78, "end": total_duration * 0.93},
            {"section": "ending", "start": total_duration * 0.93, "end": total_duration},
        ]
    else:
        sections = [
            {"section": "hook", "start": 0.0, "end": total_duration * 0.12},
            {"section": "setup", "start": total_duration * 0.12, "end": total_duration * 0.25},
            {"section": "body", "start": total_duration * 0.25, "end": total_duration * 0.78},
            {"section": "payoff", "start": total_duration * 0.78, "end": total_duration * 0.92},
            {"section": "ending", "start": total_duration * 0.92, "end": total_duration},
        ]
    for s in sections:
        s["start"] = round(max(0.0, s["start"]), 3)
        s["end"] = round(min(total_duration, max(s["start"], s["end"])), 3)
        s["duration"] = round(s["end"] - s["start"], 3)
    return sections


def attach_section_labels(plan, total_duration):
    output = []
    for item in plan or []:
        mid = (float(item["start"]) + float(item["end"])) / 2
        section = section_for_progress(mid / max(0.01, float(total_duration)))
        new = dict(item)
        new["section"] = section
        new["priority"] = SECTION_RULES.get(section, {}).get("priority", 0.5)
        output.append(new)
    return output


def pacing_density_report(plan):
    if not plan:
        return {"clip_count": 0}
    durations = [float(x.get("duration", 0.0)) for x in plan]
    sections = {}
    for item in plan:
        sec = item.get("section", "body")
        sections.setdefault(sec, {"count": 0, "duration": 0.0})
        sections[sec]["count"] += 1
        sections[sec]["duration"] += float(item.get("duration", 0.0))
    for sec in sections:
        sections[sec]["duration"] = round(sections[sec]["duration"], 3)
    return {
        "clip_count": len(plan),
        "total_duration": round(sum(durations), 3),
        "avg_clip_duration": round(sum(durations) / len(durations), 3),
        "min_clip_duration": round(min(durations), 3),
        "max_clip_duration": round(max(durations), 3),
        "sections": sections,
    }


def optimize_plan_for_clip_count(plan, desired_max=None):
    if not plan:
        return []
    if desired_max is None or len(plan) <= int(desired_max):
        return plan
    desired_max = max(1, int(desired_max))
    total = plan[-1]["end"]
    avg = float(total) / desired_max
    new_plan = []
    cursor = 0.0
    for i in range(desired_max):
        end = total if i == desired_max - 1 else cursor + avg
        section = section_for_progress(cursor / max(0.01, total))
        new_plan.append({"clip_index": i, "start": round(cursor, 3), "end": round(end, 3), "duration": round(end - cursor, 3), "section": section, "priority": SECTION_RULES.get(section, {}).get("priority", 0.5), "progress": round(cursor / max(0.01, total), 4)})
        cursor = end
    return new_plan


def expand_plan_for_minimum_clips(plan, desired_min=6):
    if not plan:
        return []
    desired_min = int(desired_min or 0)
    if len(plan) >= desired_min:
        return plan
    total = plan[-1]["end"]
    return build_even_plan(total, desired_min)


def build_even_plan(total_duration, clip_count):
    total_duration = max(0.05, float(total_duration or 0.0))
    clip_count = max(1, int(clip_count or 1))
    dur = total_duration / clip_count
    out = []
    cursor = 0.0
    for i in range(clip_count):
        end = total_duration if i == clip_count - 1 else cursor + dur
        section = section_for_progress(cursor / total_duration)
        out.append({"clip_index": i, "start": round(cursor, 3), "end": round(end, 3), "duration": round(end - cursor, 3), "section": section, "priority": SECTION_RULES.get(section, {}).get("priority", 0.5), "progress": round(cursor / total_duration, 4)})
        cursor = end
    return out


