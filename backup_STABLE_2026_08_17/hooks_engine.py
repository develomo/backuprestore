def trim_video_ffmpeg(input_path, output_path=None, duration=3.0, mode="SHORT"):
    input_path = _validate_file(input_path, "hook_video")
    output_path = Path(output_path or TEMP_DIR / f"{input_path.stem}_hook_trim.mp4")
    output_path.parent.mkdir(parents=True, exist_ok=True)
    duration = max(0.2, float(duration or 3.0))
    cmd = [
        "ffmpeg", "-y",
        "-i", str(input_path),
        "-t", str(duration),
        "-an",
        "-c:v", "libx264",
        "-preset", "veryfast",
        "-crf", "18",
        "-pix_fmt", "yuv420p",
        str(output_path),
    ]
    _run(cmd, label="trim_hook_video")
    return str(output_path)


def make_hook_text_overlay(text, duration=3.0, mode="SHORT", size=None):
    if TextClip is None:
        return None
    mode = _mode_key(mode)
    if size is None:
        size = size_for_mode(mode, quality="edit")
    w, h = size
    fontsize = int(h * (0.070 if mode == "SHORT" else 0.060))
    try:
        clip = TextClip(text, fontsize=fontsize, color="white", font="Arial-Bold", stroke_color="black", stroke_width=3, method="caption", size=(int(w * 0.86), None))
    except Exception:
        try:
            clip = TextClip(text, fontsize=fontsize, color="white", stroke_color="black", stroke_width=3)
        except Exception:
            return None
    clip = clip.set_duration(duration).set_position(("center", int(h * (0.72 if mode == "SHORT" else 0.76))))
    try:
        clip = clip.crossfadein(0.15).crossfadeout(0.20)
    except Exception:
        pass
    return clip


def apply_hook_motion(clip, profile):
    if clip is None or vfx is None:
        return clip
    motion = profile.get("motion", "clean_push")
    duration = clip_duration(clip)
    if motion in ("slow_hold", "soft_reveal"):
        amount = 0.018
    elif motion in ("dark_creep", "premium_push"):
        amount = 0.035
    else:
        amount = 0.045
    def zoom(t):
        p = min(max(t / max(duration, 0.1), 0.0), 1.0)
        eased = 1 - (1 - p) ** 3
        return 1.0 + amount * eased
    try:
        return clip.fx(vfx.resize, zoom).set_duration(duration)
    except Exception:
        return clip


def create_hook_clip_from_video(input_path, mode="SHORT", niche=None, render_count=0, hook_text=None, duration=None, strategy="smart"):
    if VideoFileClip is None:
        raise RuntimeError("MoviePy unavailable.")
    profile = _profile(niche=niche, mode=mode, render_count=render_count)
    duration = float(duration or profile["hook_duration"])
    clip = load_video_clip(input_path, audio=False)
    try:
        clip = clip.subclip(0, min(duration, clip_duration(clip)))
    except Exception:
        clip = clip.set_duration(duration)
    clip = format_clip_by_mode(clip, mode=mode, strategy=strategy, quality="edit")
    clip = apply_hook_motion(clip, profile)
    text = choose_hook_text(niche=niche, render_count=render_count, custom_text=hook_text)
    overlay = make_hook_text_overlay(text, duration=clip_duration(clip), mode=mode, size=clip.size)
    if overlay is not None and CompositeVideoClip is not None:
        try:
            clip = CompositeVideoClip([clip, overlay], size=clip.size).set_duration(clip_duration(clip))
        except Exception:
            pass
    return clip


def create_solid_hook_clip(mode="SHORT", niche=None, render_count=0, hook_text=None, duration=None):
    if ColorClip is None:
        return None
    profile = _profile(niche=niche, mode=mode, render_count=render_count)
    duration = float(duration or profile["hook_duration"])
    size = size_for_mode(mode, quality="edit")
    key = profile.get("style", "default")
    color = (8, 12, 24)
    if "mystery" in key or profile["niche"] == "mystery":
        color = (8, 6, 16)
    elif profile["niche"] == "luxury_lifestyle":
        color = (20, 16, 10)
    elif profile["niche"] == "finance_simulation":
        color = (8, 16, 12)
    bg = ColorClip(size=size, color=color, duration=duration)
    text = choose_hook_text(niche=niche, render_count=render_count, custom_text=hook_text)
    overlay = make_hook_text_overlay(text, duration=duration, mode=mode, size=size)
    if overlay is not None and CompositeVideoClip is not None:
        return CompositeVideoClip([bg, overlay], size=size).set_duration(duration)
    return bg


def create_hook_clip(mode="SHORT", niche=None, render_count=0, hook_text=None, duration=None, video_path=None, custom_folder=None, strategy="smart"):
    chosen = choose_hook_video(mode=mode, niche=niche, render_count=render_count, custom_folder=custom_folder, explicit_path=video_path)
    if chosen is not None:
        try:
            return create_hook_clip_from_video(chosen, mode=mode, niche=niche, render_count=render_count, hook_text=hook_text, duration=duration, strategy=strategy)
        except Exception as e:
            safe_print(f"[HooksEngine] hook video failed: {e}")
    return create_solid_hook_clip(mode=mode, niche=niche, render_count=render_count, hook_text=hook_text, duration=duration)


def prepend_hook_to_video(main_video, hook_clip):
    if main_video is None:
        return hook_clip
    if hook_clip is None:
        return main_video
    if concatenate_videoclips is None:
        return main_video
    try:
        return concatenate_videoclips([hook_clip, main_video], method="compose")
    except Exception:
        return main_video


def prepend_hook_to_file(video_path, output_path=None, mode="SHORT", niche=None, render_count=0, hook_text=None, duration=None, video_hook_path=None):
    if VideoFileClip is None:
        raise RuntimeError("MoviePy unavailable.")
    video_path = _validate_file(video_path, "video")
    output_path = Path(output_path or OUTPUT_DIR / f"{video_path.stem}_with_hook.mp4")
    output_path.parent.mkdir(parents=True, exist_ok=True)
    main = load_video_clip(video_path, audio=False)
    hook = create_hook_clip(mode=mode, niche=niche, render_count=render_count, hook_text=hook_text, duration=duration, video_path=video_hook_path)
    final = prepend_hook_to_video(main, hook)
    try:
        final.write_videofile(str(output_path), fps=30, codec="libx264", audio=False, preset="veryfast", threads=4)
    finally:
        for c in (main, hook, final):
            try:
                c.close()
            except Exception:
                pass
    return str(output_path)


def ffmpeg_prepend_hook(video_path, hook_path, output_path=None):
    video_path = _validate_file(video_path, "video")
    hook_path = _validate_file(hook_path, "hook")
    output_path = Path(output_path or OUTPUT_DIR / f"{video_path.stem}_ffmpeg_hook.mp4")
    output_path.parent.mkdir(parents=True, exist_ok=True)
    list_file = TEMP_DIR / "hook_concat.txt"
    list_file.write_text(f"file '{hook_path.resolve()}'\nfile '{video_path.resolve()}'", encoding="utf-8")
    cmd = ["ffmpeg", "-y", "-f", "concat", "-safe", "0", "-i", str(list_file), "-c", "copy", str(output_path)]
    result = subprocess.run(cmd, capture_output=True, text=True, shell=False)
    if result.returncode != 0:
        cmd = ["ffmpeg", "-y", "-f", "concat", "-safe", "0", "-i", str(list_file), "-c:v", "libx264", "-preset", "veryfast", "-crf", "18", "-an", str(output_path)]
        _run(cmd, label="ffmpeg_prepend_hook_reencode")
    return str(output_path)


def build_hook_plan(mode="SHORT", niche=None, render_count=0, voice_path=None, custom_text=None):
    profile = _profile(niche=niche, mode=mode, render_count=render_count)
    voice_duration = get_voice_duration_float(voice_path) if voice_path else None
    hook_text = choose_hook_text(niche=niche, render_count=render_count, custom_text=custom_text)
    video_asset = choose_hook_video(mode=mode, niche=niche, render_count=render_count)
    audio_asset = choose_hook_audio(mode=mode, niche=niche, render_count=render_count)
    return {
        "mode": profile["mode"],
        "niche": profile["niche"],
        "hook_duration": round(profile["hook_duration"], 3),
        "style": profile["style"],
        "motion": profile["motion"],
        "sound": profile["sound"],
        "energy": profile["energy"],
        "hook_text": hook_text,
        "voice_duration": round(voice_duration, 3) if voice_duration is not None else None,
        "video_asset": str(video_asset) if video_asset else None,
        "audio_asset": str(audio_asset) if audio_asset else None,
    }


def save_hook_plan(plan, output_path=None):
    output_path = Path(output_path or REPORT_DIR / "hook_plan.json")
    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text(json.dumps(plan, indent=2, ensure_ascii=False, default=str), encoding="utf-8")
    return str(output_path)


def hooks_engine_report(mode="SHORT", niche=None, render_count=0):
    return {
        "output_dir": str(OUTPUT_DIR),
        "temp_dir": str(TEMP_DIR),
        "report_dir": str(REPORT_DIR),
        "mode": _mode_key(mode),
        "niche": _resolve_niche(niche),
        "profile": _profile(niche=niche, mode=mode, render_count=render_count),
        "video_assets": [str(p) for p in list_hook_video_assets(mode=mode)[:30]],
        "audio_assets": [str(p) for p in list_hook_audio_assets(mode=mode)[:30]],
        "moviepy_available": VideoFileClip is not None,
    }


class HooksEngine:
    def __init__(self, mode="SHORT", niche=None, render_count=0):
        self.mode = _mode_key(mode)
        self.niche = niche or "default"
        self.render_count = int(render_count or 0)

    def plan(self, voice_path=None, custom_text=None):
        return build_hook_plan(mode=self.mode, niche=self.niche, render_count=self.render_count, voice_path=voice_path, custom_text=custom_text)

    def create(self, hook_text=None, duration=None, video_path=None, custom_folder=None):
        return create_hook_clip(mode=self.mode, niche=self.niche, render_count=self.render_count, hook_text=hook_text, duration=duration, video_path=video_path, custom_folder=custom_folder)

    def prepend(self, main_video, hook_clip=None, hook_text=None):
        hook_clip = hook_clip or self.create(hook_text=hook_text)
        return prepend_hook_to_video(main_video, hook_clip)

    def file(self, video_path, output_path=None, hook_text=None, duration=None, video_hook_path=None):
        return prepend_hook_to_file(video_path, output_path=output_path, mode=self.mode, niche=self.niche, render_count=self.render_count, hook_text=hook_text, duration=duration, video_hook_path=video_hook_path)

    def report(self):
        return hooks_engine_report(mode=self.mode, niche=self.niche, render_count=self.render_count)


def add_hook(video, mode="SHORT", niche=None, render_count=0, hook_text=None):
    hook = create_hook_clip(mode=mode, niche=niche, render_count=render_count, hook_text=hook_text)
    return prepend_hook_to_video(video, hook)


