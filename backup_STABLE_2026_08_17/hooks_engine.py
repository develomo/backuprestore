def safe_print(message):
    try:
        print(str(message).replace("→", "->").replace("—", "-").replace("–", "-"), flush=True)
    except Exception:
        pass


def _mode_key(mode="SHORT"):
    mode = str(mode or "SHORT").upper()
    if mode in ("LONG", "YOUTUBE_LONG", "HORIZONTAL"):
        return "LONG"
    return "SHORT"


def _resolve_niche(niche=None):
    key = str(niche or "default").strip().lower()
    return key if key in HOOK_PROFILES else "default"


def _profile(niche=None, mode="SHORT", render_count=0):
    key = _resolve_niche(niche)
    data = dict(HOOK_PROFILES[key])
    mode = _mode_key(mode)
    base = data["long_hook_duration"] if mode == "LONG" else data["short_hook_duration"]
    offset = ((int(render_count or 0) % 5) - 2) * 0.12
    data["hook_duration"] = max(1.2, min(5.0, base + offset))
    data["niche"] = key
    data["mode"] = mode
    return data


def _validate_file(path, label="file"):
    p = Path(path)
    if not p.exists():
        raise FileNotFoundError(f"{label} not found: {p}")
    return p


def _run(cmd, label="ffmpeg"):
    result = subprocess.run(cmd, capture_output=True, text=True, shell=False)
    if result.returncode != 0:
        safe_print(result.stderr)
        raise RuntimeError(f"{label} failed")
    return result.stdout


def _ffprobe_duration(path):
    p = Path(path)
    cmd = ["ffprobe", "-v", "error", "-show_entries", "format=duration", "-of", "json", str(p)]
    try:
        result = subprocess.run(cmd, capture_output=True, text=True, shell=False)
        if result.returncode != 0:
            return 0.0
        return float(json.loads(result.stdout).get("format", {}).get("duration", 0.0) or 0.0)
    except Exception:
        return 0.0


def clip_duration(clip):
    try:
        return max(float(clip.duration), 0.05)
    except Exception:
        return 0.05


def list_hook_video_assets(mode="SHORT", custom_folder=None):
    folders = []
    if custom_folder:
        folders.append(Path(custom_folder))
    if _mode_key(mode) == "LONG":
        folders.extend([ASSETS_DIR / "long" / "hook", ASSETS_DIR / "hook", ASSETS_DIR / "long" / "clips"])
    else:
        folders.extend([ASSETS_DIR / "shorts" / "hook", ASSETS_DIR / "hook", ASSETS_DIR / "shorts" / "clips"])
    files = []
    for folder in folders:
        if not folder.exists():
            continue
        files.extend([p for p in folder.iterdir() if p.is_file() and p.suffix.lower() in VIDEO_EXTS])
    return sorted(_dedupe(files), key=lambda p: p.name.lower())


